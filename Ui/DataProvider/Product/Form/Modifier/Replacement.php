    public const GROUP_REPLACEMENT = 'replacement';

    /**
     * EAV attribute group ("Replacement Products") created by
     * CreateReplacementProductsAttributeGroup - used only as a source to pull the
     * already-built "is_discontinued" Field component from, then relocated into this
     * modifier's own top-level Fieldset group below.
