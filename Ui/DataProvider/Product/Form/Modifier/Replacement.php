    public function __construct(
        LocatorInterface $locator,
        UrlInterface $urlBuilder,
        ProductLinkRepositoryInterface $productLinkRepository,
        ProductRepositoryInterface $productRepository,
        ImageHelper $imageHelper,
        Status $status,
        AttributeSetRepositoryInterface $attributeSetRepository,
        $scopeName = '',
        $scopePrefix = ''
    ) {
        $this->locator = $locator;
        $this->urlBuilder = $urlBuilder;
        $this->productLinkRepository = $productLinkRepository;
        $this->productRepository = $productRepository;
        $this->imageHelper = $imageHelper;
        $this->status = $status;
        $this->attributeSetRepository = $attributeSetRepository;
        $this->scopeName = $scopeName;
        $this->scopePrefix = $scopePrefix;
    }

    /**
     * @inheritdoc
     *
     */
    public function modifyMeta(array $meta)
    {
        $replacementFieldset = $this->getReplacementFieldset();

        // Attribute codes to pull out of the auto-rendered EAV group, in display order.
        // Only "is_discontinued" gets an explicit sortOrder (0, matching the original
        // single-field behavior). The redirect fields are left without one so they simply
        // append after whatever was already inserted - see the note on getGrid() below for
        // why mixing explicit indexes with this "no sortOrder = append" style is important:
        // sortOrder is an insertion INDEX (Magento_Ui/js/lib/core/collection.js insertChild),
        // not a comparator key, so a later sibling with a stale hardcoded index reinserts
        // itself ahead of whatever already occupies that slot instead of just appending.
        $relocatedFields = [
            'is_discontinued' => 0,
            'discontinued_redirect_enabled' => null,
            'discontinued_redirect_sku' => null,
        ];

        $relocated = [];
        foreach ($relocatedFields as $attributeCode => $sortOrder) {
            $container = static::CONTAINER_PREFIX . $attributeCode;
            if (!isset($meta[self::EAV_GROUP_CODE]['children'][$container])) {
                continue;
            }

            $field = $meta[self::EAV_GROUP_CODE]['children'][$container];
            unset($meta[self::EAV_GROUP_CODE]['children'][$container]);

            // Re-anchor to "data.product" explicitly: this field no longer lives inside the
            // eav group (which supplied that prefix to all its children), so without this
            // override the field would resolve to the wrong, unprefixed dataScope here.
            $field['arguments']['data']['config']['dataScope'] = static::DATA_SCOPE_PRODUCT;
            if ($sortOrder !== null) {
                $field['arguments']['data']['config']['sortOrder'] = $sortOrder;
            }

            $relocated[$container] = $field;
        }

        // Always shown alongside the toggle (rather than hidden/shown dynamically) -
        // it's only read when "Redirect to Another Product" is on, see ValidateRedirectSku.
        $redirectSkuContainer = static::CONTAINER_PREFIX . 'discontinued_redirect_sku';
        if (isset($relocated[$redirectSkuContainer])) {
            $relocated[$redirectSkuContainer]['arguments']['data']['config']['notice'] =
                __('Only used when "Redirect to Another Product" is set to Yes.');
        }

        if ($relocated) {
            $replacementFieldset['children'] = $relocated + $replacementFieldset['children'];

            // The EAV group only ever held these attributes - now that they've been
            // relocated, the group itself is empty and would otherwise still render
            // as a blank collapsible panel.
            unset($meta[self::EAV_GROUP_CODE]);
        }

        $meta = array_replace_recursive(
            $meta,
            [
                static::GROUP_REPLACEMENT => [
                    'children' => [
                        $this->scopePrefix . static::GROUP_REPLACEMENT => $replacementFieldset,
                    ],
                    'arguments' => [
                        'data' => [
                            'config' => [
                                'label' => __('Discontinued Products'),
                                'collapsible' => true,
                                'componentType' => Fieldset::NAME,
                                'dataScope' => static::DATA_SCOPE,
                                'sortOrder' => $this->getNextGroupSortOrder(
                                    $meta,
                                    self::$previousGroup,
                                    self::$sortOrder
                                ),
                            ],
                        ],

                    ],
                ],
            ]
        );

        return $meta;
    }

    /**
     * @inheritdoc
     *
     */
    public function modifyData(array $data)
    {
        /** @var \Magento\Catalog\Model\Product $product */
        $product = $this->locator->getProduct();
        $productId = $product->getId();

        if (!$productId) {
            return $data;
        }

        $priceModifier = $this->getPriceModifier();
        /**
         * Set field name for modifier
         */
        $priceModifier->setData('name', 'price');

        foreach ($this->getDataScopes() as $dataScope) {
            $data[$productId]['links'][$dataScope] = [];
            $linkItems = [];
            foreach ($this->productLinkRepository->getList($product) as $linkItem) {
                if ($linkItem->getLinkType() !== $dataScope) {
                    continue;
                }
                $linkItems[] = $linkItem;
            }
            usort($linkItems, function ($a, $b) {
                return $a->getPosition() <=> $b->getPosition();
            });
            foreach ($linkItems as $linkItem) {
                /** @var \Magento\Catalog\Model\Product $linkedProduct */
                $linkedProduct = $this->productRepository->get(
                    $linkItem->getLinkedProductSku(),
                    false,
                    $this->locator->getStore()->getId()
                );
                $data[$productId]['links'][$dataScope][] = $this->fillData($linkedProduct, $linkItem);
            }
            if (!empty($data[$productId]['links'][$dataScope])) {
                $dataMap = $priceModifier->prepareDataSource([
                    'data' => [
                        'items' => $data[$productId]['links'][$dataScope]
                    ]
                ]);
                $data[$productId]['links'][$dataScope] = $dataMap['data']['items'];
            }
        }

        $data[$productId][self::DATA_SOURCE_DEFAULT]['current_product_id'] = $productId;
        $data[$productId][self::DATA_SOURCE_DEFAULT]['current_store_id'] = $this->locator->getStore()->getId();

        return $data;
    }

    /**
     * Get price modifier
     *
     * @return \Magento\Catalog\Ui\Component\Listing\Columns\Price
     */
    private function getPriceModifier()
    {
        if (!$this->priceModifier) {
            $this->priceModifier = ObjectManager::getInstance()->get(
                \Magento\Catalog\Ui\Component\Listing\Columns\Price::class
            );
        }
        return $this->priceModifier;
    }

    /**
     * Prepare data column
     *
     * @param ProductInterface $linkedProduct
     * @param ProductLinkInterface $linkItem
     * @return array
     */
    protected function fillData(ProductInterface $linkedProduct, ProductLinkInterface $linkItem)
    {
        return [
            'id' => $linkedProduct->getId(),
            'thumbnail' => $this->imageHelper->init($linkedProduct, 'product_listing_thumbnail')->getUrl(),
            'name' => $linkedProduct->getName(),
            'status' => $this->status->getOptionText($linkedProduct->getStatus()),
            'attribute_set' => $this->attributeSetRepository
                ->get($linkedProduct->getAttributeSetId())
                ->getAttributeSetName(),
            'sku' => $linkItem->getLinkedProductSku(),
            'price' => $linkedProduct->getPrice(),
            'position' => $linkItem->getPosition(),
        ];
    }

    /**
     * Prepares config for the Replacement Products fieldset
     *
     * @return array
     * @since 101.0.0
     */
    protected function getReplacementFieldset()
    {
        $content = __(
            'Replacement products are shown on product pages as links to alternative products when the original product is no longer being manufactured.'
        );

        return [
            'children' => [
                'button_set' => $this->getButtonSet(
                    $content,
                    __('Add Replacement Products'),
                    $this->scopePrefix . static::DATA_SCOPE_REPLACEMENT
                ),
                'modal' => $this->getGenericModal(
                    __('Add Replacement Products'),
                    $this->scopePrefix . static::DATA_SCOPE_REPLACEMENT
                ),
                static::DATA_SCOPE_REPLACEMENT => $this->getGrid($this->scopePrefix . static::DATA_SCOPE_REPLACEMENT),
            ],
            'arguments' => [
                'data' => [
                    'config' => [
                        'additionalClasses' => 'admin__fieldset-section',
                        'label' => __('Replacement Products'),
                        'collapsible' => false,
                        'componentType' => Fieldset::NAME,
                        'dataScope' => '',
                        'sortOrder' => 10,
                    ],
                ],
            ]
        ];
    }

    /**
     * Retrieve button set
     *
     * @param Phrase $content
     * @param Phrase $buttonTitle
     * @param string $scope
     * @return array
     */
    protected function getButtonSet(Phrase $content, Phrase $buttonTitle, $scope)
    {
        $modalTarget = $this->scopeName . '.' . static::GROUP_REPLACEMENT . '.' . $scope . '.modal';

        return [
            'arguments' => [
                'data' => [
                    'config' => [
                        'formElement' => 'container',
                        'componentType' => 'container',
                        'label' => false,
                        'content' => $content,
                        'template' => 'ui/form/components/complex',
                    ],
                ],
            ],
            'children' => [
                'button_' . $scope => [
                    'arguments' => [
                        'data' => [
                            'config' => [
                                'formElement' => 'container',
                                'componentType' => 'container',
                                'component' => 'Magento_Ui/js/form/components/button',
                                'actions' => [
                                    [
                                        'targetName' => $modalTarget,
                                        'actionName' => 'toggleModal',
                                    ],
                                    [
                                        'targetName' => $modalTarget . '.' . $scope . '_product_listing',
                                        'actionName' => 'render',
                                    ]
                                ],
                                'title' => $buttonTitle,
                                'provider' => null,
                            ],
                        ],
                    ],

                ],
            ],
        ];
    }

    /**
